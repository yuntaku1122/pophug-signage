#
# ボタンはUSB-Aポートに挿すだけで使えるUSB HID（キーボードエミュレーション）式の
# 押しボタンスイッチを想定している。この種の製品はOS標準のキーボードドライバで
# 認識されるため、Pi側で追加のドライバ・sudoers設定・GPIO配線は一切不要で、
# 挿すだけで「特定のキーが押された」という通常のキー入力として届く。
#
# どのキーコードを送ってくるかは製品によって異なる（初期設定のまま使う場合が
# 多いが、専用ツールで変更できる製品もある）ため、本体側では特定のキーコードを
# 決め打ちにしていない。Web設定画面が「直前に検出した、まだ何にも割り当てられて
# いないキー」を表示するので、購入したボタンを一度押すだけでどのキーか分かり、
# そのままワンクリックで割り当てられる（main.pyのsave_last_detected_key参照）。
