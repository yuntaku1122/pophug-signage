# USB書き出し（吸い出し）機能設定
# 「今格納されている画像を全部USBメモリーに書き出したい」という要望への対応。
# 2通りの起動経路がある：
#   A. Web設定画面から（PCからブラウザでアクセスしている場合）
#      画面の「今すぐUSBへ書き出す」ボタンを押すだけで、その場でUSBメモリーへ
#      書き出す。Web設定画面に入れていること自体を許可の根拠とするため、
#      合言葉ファイルは不要（詳細はpophug-usb-importのmanual_export()）。
#   B. 本体ボタンの機能メニュー（PCレス運用時）
#      1. 本体ボタンを押して機能メニューを開き、「USB書き出し待受け」を長押しで決定して
#         「書き出し待受けモード」に入る
#      2. 待受け中に挿したUSBメモリーの直下に、この機体のホスト名が1行として
#         書かれたテキストファイル（EXPORT_KEY_FILENAME）が置かれていた場合だけ、
#         実際に書き出しを行う。ここでの「合言葉」は秘密の値ではなく、単に
#         「このUSBでの書き出しを許可された機体のホスト名一覧」を意味する
#         （機密性を高める必要は無いという前提の設計）。1つのファイルに複数の
#         ホスト名を1行ずつ書いておけば、そのUSB1本を複数のpophug本体に順番に
#         挿すだけで、それぞれの機体から書き出せる（マスターUSB運用）。
#      ホスト名が書かれていない・ファイル自体が無い場合は書き出しは行われず、
#      通常のUSB取り込み動作だけが行われる（待受け状態はそのまま残り、
#      USBを挿し直して再挑戦できる）。誤って画像を抜かれることは無い。
EXPORT_STANDBY_TIMEOUT_SECONDS = 180  # 待受けモードのままUSBが挿されなかった場合に
                                       # 自動キャンセルするまでの秒数
EXPORT_KEY_FILENAME = "pophug-export-key.txt"  # USB直下に置く、許可ホスト名一覧ファイル名
                                                # （大文字小文字は区別しない）

